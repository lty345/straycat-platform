# 【为什么种子数据要"按维度造"】
#   推荐算法有三个输入：标签匹配、情绪偏好、时间衰减。
#   如果 20 条数据全是"今天发的 + 同一个 mood + 同一个 tag"，
#   那么调算法时你看到的分数几乎一样，根本验证不出任何东西。
#   所以要：
#     ① pub_time 错开（0 天到 30 天）→ 才能验证时间衰减
#     ② mood 四种全覆盖        → 才能验证情绪加权
#     ③ tags 分成几组          → 才能验证标签匹配
#
# 【可重复运行】
#   每次先清空 content 表再插入，所以跑多少次结果都一样（幂等）。
# =============================================================================
