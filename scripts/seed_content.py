async def seed() -> None:
    now = datetime.now()

    async with AsyncSessionLocal() as db:
        await db.execute(delete(Content))

        rows = [
            Content(
                title=title,
                summary=summary,
                body=STORIES.get(title, body),
                tags=tags,
                mood=mood,
                cover_url=f'/covers/p{idx + 1:02d}.jpg',
                pub_time=now - timedelta(days=days_ago),
            )
            for idx, (title, summary, body, mood, tags, days_ago, cover) in enumerate(SEED)
        ]

        db.add_all(rows)
        await db.commit()

        all_rows = (await db.execute(select(Content))).scalars().all()
        from collections import Counter

        print(f'清空并插入完成，当前 content 表共 {len(all_rows)} 条')
        print('  mood 分布:', dict(Counter(r.mood for r in all_rows)))
        print('  有封面:', sum(1 for r in all_rows if r.cover_url), '/', len(all_rows))
        print('  正文平均字数:', round(sum(len(r.body or '') for r in all_rows) / len(all_rows)))
        print('  时间跨度:', min(r.pub_time for r in all_rows).date(), '~', max(r.pub_time for r in all_rows).date())

    await async_engine.dispose()


if __name__ == '__main__':
    asyncio.run(seed())