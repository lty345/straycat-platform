async def seed() -> None:
    now = datetime.now()

    async with AsyncSessionLocal() as db:
        # ① 清空（幂等：跑多少次结果都一样）
        await db.execute(delete(Content))

        # ② 造对象
        rows = [
            Content(
                title=title,
                summary=summary,
                body=f"{summary}\n\n（占位正文，详情页用。以后可以换成真实内容。）",
                tags=tags,
                mood=mood,
                cover_url=None,
                # ★ pub_time 按 days_ago 错开，否则时间衰减测不出来
                pub_time=now - timedelta(days=days_ago),
            )
            for title, summary, mood, tags, days_ago in SEED
        ]

        # ③ 批量插入 + 提交（一个事务）
        db.add_all(rows)
        await db.commit()

        # ④ 回读确认
        result = await db.execute(select(Content))
        print(f"清空并插入完成，当前 content 表共 {len(result.scalars().all())} 条")

    await async_engine.dispose()


if __name__ == "__main__":
    asyncio.run(seed())
