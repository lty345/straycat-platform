STORIES['科普：猫为什么爱舔毛'] = '''猫清醒的时间里，有三到四成花在理毛上。

按一天十六小时算，就是五到六个小时。比很多人的运动时间都长。

最直接的原因是清洁。舔毛能带走浮尘和脱落的毛，唾液蒸发还能降温。夏天猫会舔得更勤，就是这个道理。

第二个原因是气味。猫靠气味判断「谁是自己人」。你抱完它，它转身就舔你摸过的地方——不是嫌弃，是在把陌生的味道抹掉，恢复成自己的。

第三个原因是情绪。紧张、疼痛、被打乱节奏的时候，猫会舔自己。这是一种自我安抚，和人在焦虑时搓手差不多。

所以要看的是频率的变化。

正常理毛是均匀的，全身都舔。如果一只猫突然死盯着一块地方舔，舔到脱毛、破皮、渗液，那不是洁癖，是信号——可能是皮肤病，可能是疼痛（关节炎的猫会舔疼的那条腿），也可能是焦虑。

还有一种反面情况：猫突然不舔了，毛变得油腻打结。这通常意味着它病了，没力气舔。

一天五小时的日常，加一点观察。'''

