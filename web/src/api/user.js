// =============================================================================
// ★ 为什么前端要拉用户列表，而不是把 id 写死：
//   种子脚本每次重跑都会让自增 id 往后跳（4/5/6 → 7/8/9…），
//   写死的 id 一旦对不上，页面就"用户不存在"。
//   id 是数据，不是配置 —— 从接口拿。
// =============================================================================
import client from './client'

export async function fetchUsers({ page = 1, pageSize = 50 } = {}) {
  const data = await client.get('/api/v1/users', { params: { page, page_size: pageSize } })
  return data.list ?? []
}
